import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";

export type VerifyV2ServiceEntityChallengeNotification = {
  /** A 34 character string that uniquely identifies this Notification. */
  sid?: string | null;
  /** The unique SID identifier of the Account. */
  accountSid?: string | null;
  /** The unique SID identifier of the Service. */
  serviceSid?: string | null;
  /** The unique SID identifier of the Entity. */
  entitySid?: string | null;
  /**
   * Customer unique identity for the Entity owner of the Challenge. This identifier should be
   * immutable, not PII, length between 8 and 64 characters, and generated by your external system,
   * such as your user's UUID, GUID, or SID. It can only contain dash (-) separated alphanumeric
   * characters.
   */
  identity?: string | null;
  /** The unique SID identifier of the Challenge. */
  challengeSid?: string | null;
  /**
   * The priority of the notification. For `push` Challenges it's always `high` which sends the
   * notification immediately, and can wake up a sleeping device.
   */
  priority?: string | null;
  /** How long, in seconds, the notification is valid. Max: 5 minutes @default 0 */
  ttl?: number;
  /**
   * The date that this Notification was created, given in [ISO
   * 8601](https://en.wikipedia.org/wiki/ISO_8601) format.
   */
  dateCreated?: Date | null;
};

export const verifyV2ServiceEntityChallengeNotificationSchema: Schema<VerifyV2ServiceEntityChallengeNotification> =
  s.object<VerifyV2ServiceEntityChallengeNotification>({
    sid: s.optionalNullable(s.string()),
    accountSid: s.optionalNullable(s.string()),
    serviceSid: s.optionalNullable(s.string()),
    entitySid: s.optionalNullable(s.string()),
    identity: s.optionalNullable(s.string()),
    challengeSid: s.optionalNullable(s.string()),
    priority: s.optionalNullable(s.string()),
    ttl: s.defaulted(s.int(), 0),
    dateCreated: s.optionalNullable(s.dateTime()),
    _keysMap: {
      accountSid: "account_sid",
      serviceSid: "service_sid",
      entitySid: "entity_sid",
      challengeSid: "challenge_sid",
      dateCreated: "date_created",
    },
  });
