import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import {
  newFactorEnumFactorStatusesSchema,
  type NewFactorEnumFactorStatuses,
} from "./new-factor-enum-factor-statuses.js";
import {
  newFactorEnumFactorTypesSchema,
  type NewFactorEnumFactorTypes,
} from "./new-factor-enum-factor-types.js";

export type VerifyV2ServiceEntityNewFactor = {
  /** A 34 character string that uniquely identifies this Factor. */
  sid?: string | null;
  /** The unique SID identifier of the Account. */
  accountSid?: string | null;
  /** The unique SID identifier of the Service. */
  serviceSid?: string | null;
  /** The unique SID identifier of the Entity. */
  entitySid?: string | null;
  /**
   * Customer unique identity for the Entity owner of the Factor. This identifier should be
   * immutable, not PII, length between 8 and 64 characters, and generated by your external system,
   * such as your user's UUID, GUID, or SID. It can only contain dash (-) separated alphanumeric
   * characters.
   */
  identity?: string | null;
  /**
   * Contains the `factor_type` specific secret and metadata. For push, this is `binding.public_key`
   * and `binding.alg`. For totp, this is `binding.secret` and `binding.uri`. The `binding.uri`
   * property is generated following the [google authenticator key URI
   * format](https://github.com/google/google-authenticator/wiki/Key-Uri-Format), and
   * `Factor.friendly_name` is used for the “accountname” value and `Service.friendly_name` or
   * `Service.totp.issuer` is used for the `issuer` value.
   *
   *
   * The Binding property is ONLY returned upon Factor creation.
   */
  binding?: Record<string, unknown> | null;
  options?: Record<string, unknown> | null;
  /**
   * The date that this Factor was created, given in [ISO
   * 8601](https://en.wikipedia.org/wiki/ISO_8601) format.
   */
  dateCreated?: Date | null;
  /**
   * The date that this Factor was updated, given in [ISO
   * 8601](https://en.wikipedia.org/wiki/ISO_8601) format.
   */
  dateUpdated?: Date | null;
  /**
   * The friendly name of this Factor. This can be any string up to 64 characters, meant for humans
   * to distinguish between Factors. For `factor_type` `push`, this could be a device name. For
   * `factor_type` `totp`, this value is used as the “account name” in constructing the
   * `binding.uri` property. At the same time, we recommend avoiding providing PII.
   */
  friendlyName?: string | null;
  /** The Status of this Factor. One of `unverified` or `verified`. */
  status?: NewFactorEnumFactorStatuses;
  /** The Type of this Factor. Currently `push` and `totp` are supported. */
  factorType?: NewFactorEnumFactorTypes;
  /** An object that contains configurations specific to a `factor_type`. */
  config?: Record<string, unknown> | null;
  /**
   * Custom metadata associated with the factor. This is added by the Device/SDK directly to allow
   * for the inclusion of device information. It must be a stringified JSON with only strings values
   * eg. `{"os": "Android"}`. Can be up to 1024 characters in length.
   */
  metadata?: Record<string, unknown> | null;
  /** The URL of this resource. */
  url?: string | null;
};

export const verifyV2ServiceEntityNewFactorSchema: Schema<VerifyV2ServiceEntityNewFactor> =
  s.object<VerifyV2ServiceEntityNewFactor>({
    sid: s.optionalNullable(s.string()),
    accountSid: s.optionalNullable(s.string()),
    serviceSid: s.optionalNullable(s.string()),
    entitySid: s.optionalNullable(s.string()),
    identity: s.optionalNullable(s.string()),
    binding: s.optionalNullable(s.record(s.string(), s.unknown())),
    options: s.optionalNullable(s.record(s.string(), s.unknown())),
    dateCreated: s.optionalNullable(s.dateTime()),
    dateUpdated: s.optionalNullable(s.dateTime()),
    friendlyName: s.optionalNullable(s.string()),
    status: s.optional(s.lazy(() => newFactorEnumFactorStatusesSchema)),
    factorType: s.optional(s.lazy(() => newFactorEnumFactorTypesSchema)),
    config: s.optionalNullable(s.record(s.string(), s.unknown())),
    metadata: s.optionalNullable(s.record(s.string(), s.unknown())),
    url: s.optionalNullable(s.string()),
    _keysMap: {
      accountSid: "account_sid",
      serviceSid: "service_sid",
      entitySid: "entity_sid",
      dateCreated: "date_created",
      dateUpdated: "date_updated",
      friendlyName: "friendly_name",
      factorType: "factor_type",
    },
  });
