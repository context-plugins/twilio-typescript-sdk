import type { AuthSchemes } from "../auth-schemes.js";
import { ApiError } from "../core/api-error.js";
import type { ApiPromise } from "../core/api-promise.js";
import type { RequestOptions } from "../core/api-request.js";
import type { RawClient } from "../core/raw-client.js";
import { uuid } from "../core/uuid.js";
import * as s from "../core/validation/index.js";
import {
  verifyV2ServiceEntityChallengeNotificationSchema,
  type VerifyV2ServiceEntityChallengeNotification,
} from "../models/verify-v2-service-entity-challenge-notification.js";
import type { Servers } from "../servers.js";

export class VerifyV2Notification {
  readonly #rawClient: RawClient;
  readonly #servers: Servers;
  readonly #auth: AuthSchemes;

  constructor(rawClient: RawClient, servers: Servers, auth: AuthSchemes) {
    this.#rawClient = rawClient;
    this.#servers = servers;
    this.#auth = auth;
  }

  /**
   * Create a new Notification for the corresponding Challenge
   *
   * @remarks
   * Create a new Notification for the corresponding Challenge
   *
   * @returns Created
   *
   * @throws {@link ApiError} when the API answers with an error status
   *
   * @throws {@link TwilioSdkError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  createNotification(
    request: VerifyV2Notification.CreateNotificationRequest,
    options?: RequestOptions,
  ): ApiPromise<VerifyV2ServiceEntityChallengeNotification, ApiError> {
    return this.#rawClient.execute(
      {
        method: "POST",
        urlTemplate: this.#servers.default3(
          "/v2/Services/{ServiceSid}/Entities/{Identity}/Challenges/{ChallengeSid}/Notifications",
        ),
        auth: this.#auth.accountSidAuthToken,
        pathParams: [
          { name: "ServiceSid", value: request.serviceSid, schema: s.string() },
          { name: "Identity", value: request.identity, schema: s.string() },
          { name: "ChallengeSid", value: request.challengeSid, schema: s.string() },
        ],
        query: [],
        headers: [{ name: "Idempotency-Key", value: uuid(), schema: s.string() }],
        body: {
          kind: "formUrlEncoded",
          value: [{ name: "Ttl", value: request.ttl, schema: s.optional(s.int()) }],
        },
      },
      {
        success: { kind: "json", schema: verifyV2ServiceEntityChallengeNotificationSchema },
        errorFactory: ApiError,
      },
      options,
    );
  }
}

export namespace VerifyV2Notification {
  export type CreateNotificationRequest = {
    /** The unique SID identifier of the Service. */
    serviceSid: string;
    /**
     * Customer unique identity for the Entity owner of the Challenge. This identifier should be
     * immutable, not PII, length between 8 and 64 characters, and generated by your external
     * system, such as your user's UUID, GUID, or SID. It can only contain dash (-) separated
     * alphanumeric characters.
     */
    identity: string;
    /** The unique SID identifier of the Challenge. */
    challengeSid: string;
    /**
     * How long, in seconds, the notification is valid. Can be an integer between 0 and 300. Default
     * is 300. Delivery is attempted until the TTL elapses, even if the device is offline. 0 means
     * that the notification delivery is attempted immediately, only once, and is not stored for
     * future delivery.
     */
    ttl?: number;
  };
}
