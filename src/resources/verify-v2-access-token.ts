import type { AuthSchemes } from "../auth-schemes.js";
import { ApiError } from "../core/api-error.js";
import type { ApiPromise } from "../core/api-promise.js";
import type { RequestOptions } from "../core/api-request.js";
import type { RawClient } from "../core/raw-client.js";
import { uuid } from "../core/uuid.js";
import * as s from "../core/validation/index.js";
import {
  accessTokenEnumFactorTypesSchema,
  type AccessTokenEnumFactorTypes,
} from "../models/access-token-enum-factor-types.js";
import {
  verifyV2ServiceAccessTokenSchema,
  type VerifyV2ServiceAccessToken,
} from "../models/verify-v2-service-access-token.js";
import type { Servers } from "../servers.js";

export class VerifyV2AccessToken {
  readonly #rawClient: RawClient;
  readonly #servers: Servers;
  readonly #auth: AuthSchemes;

  constructor(rawClient: RawClient, servers: Servers, auth: AuthSchemes) {
    this.#rawClient = rawClient;
    this.#servers = servers;
    this.#auth = auth;
  }

  /**
   * Create a new enrollment Access Token for the Entity
   *
   * @remarks
   * Create a new enrollment Access Token for the Entity
   *
   * @returns Created
   *
   * @throws {@link ApiError} when the API answers with an error status
   *
   * @throws {@link TwilioSdkError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  createAccessToken(
    request: VerifyV2AccessToken.CreateAccessTokenRequest,
    options?: RequestOptions,
  ): ApiPromise<VerifyV2ServiceAccessToken, ApiError> {
    return this.#rawClient.execute(
      {
        method: "POST",
        urlTemplate: this.#servers.default3("/v2/Services/{ServiceSid}/AccessTokens"),
        auth: this.#auth.accountSidAuthToken,
        pathParams: [{ name: "ServiceSid", value: request.serviceSid, schema: s.string() }],
        query: [],
        headers: [{ name: "Idempotency-Key", value: uuid(), schema: s.string() }],
        body: {
          kind: "formUrlEncoded",
          value: [
            { name: "Identity", value: request.identity, schema: s.string() },
            { name: "FactorType", value: request.factorType, schema: accessTokenEnumFactorTypesSchema },
            { name: "FactorFriendlyName", value: request.factorFriendlyName, schema: s.optional(s.string()) },
            { name: "Ttl", value: request.ttl, schema: s.optional(s.int()) },
          ],
        },
      },
      {
        success: { kind: "json", schema: verifyV2ServiceAccessTokenSchema },
        errorFactory: ApiError,
      },
      options,
    );
  }

  /**
   * Fetch an Access Token for the Entity
   *
   * @remarks
   * Fetch an Access Token for the Entity
   *
   * @returns OK
   *
   * @throws {@link ApiError} when the API answers with an error status
   *
   * @throws {@link TwilioSdkError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  fetchAccessToken(
    request: VerifyV2AccessToken.FetchAccessTokenRequest,
    options?: RequestOptions,
  ): ApiPromise<VerifyV2ServiceAccessToken, ApiError> {
    return this.#rawClient.execute(
      {
        method: "GET",
        urlTemplate: this.#servers.default3("/v2/Services/{ServiceSid}/AccessTokens/{Sid}"),
        auth: this.#auth.accountSidAuthToken,
        pathParams: [
          { name: "ServiceSid", value: request.serviceSid, schema: s.string() },
          { name: "Sid", value: request.sid, schema: s.string() },
        ],
        query: [],
        headers: [],
        body: { kind: "empty" },
      },
      {
        success: { kind: "json", schema: verifyV2ServiceAccessTokenSchema },
        errorFactory: ApiError,
      },
      options,
    );
  }
}

export namespace VerifyV2AccessToken {
  export type CreateAccessTokenRequest = {
    /** The unique SID identifier of the Service. */
    serviceSid: string;
    /**
     * The unique external identifier for the Entity of the Service. This identifier should be
     * immutable, not PII, and generated by your external system, such as your user's UUID, GUID, or
     * SID.
     */
    identity: string;
    /** The Type of the Factor. Currently only `push` is supported. */
    factorType: AccessTokenEnumFactorTypes;
    /** The friendly name of the factor that is going to be created with this access token */
    factorFriendlyName?: string;
    /**
     * How long, in seconds, the access token is valid. Can be an integer between 60 and 300.
     * Default is 60.
     */
    ttl?: number;
  };

  export type FetchAccessTokenRequest = {
    /** The unique SID identifier of the Service. */
    serviceSid: string;
    /** A 34 character string that uniquely identifies this Access Token. */
    sid: string;
  };
}
